#!/usr/bin/env bash
set -uo pipefail

# retro.sh — generates the measured part of retro.md from state.md,
# decisions.md, and the review files, so the Lead writes only the judgment.
# It also records which reviewer checks fired in <research-root>/rule-hits.tsv
# and lists checks that have not fired in the last 5 runs: candidates to
# retire as models stop making the mistake they guard against.
#
# Usage: retro.sh --workspace DIR > <workspace>/retro.md   (then append the judgment)

WORKSPACE=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --workspace) WORKSPACE="$2"; shift 2 ;;
    *) sed -n '4,10p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 2 ;;
  esac
done
W="$WORKSPACE"; STATE="$W/state.md"; DEC="$W/decisions.md"
[[ -f "$STATE" ]] || { echo "retro: no $STATE" >&2; exit 2; }
ROOT="$(cd "$W/../.." && pwd)"; HITS="$ROOT/rule-hits.tsv"
REVIEWER="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/agents/dm-rs-reviewer/SKILL.md"
field()   { grep -m1 "^$1:" "$STATE" | sed "s/^$1:[[:space:]]*//"; }
section() { awk -v h="## $1" 'index($0,h)==1{on=1; next} on && /^## /{exit} on' "$STATE"; }
RUN="$(field run)"

echo "# Retro: $RUN"
echo
echo "Kind $(field kind), size $(field size), mode $(field mode), max-parallel $(field max-parallel), waves $(field wave). Generated by scripts/retro.sh on $(date -u +%F)."
echo
echo "## Gates"
echo
echo "| Gate | Status | Round | Notes |"; echo "|---|---|---|---|"
section Gates | awk -F'|' '/^\| / && $2 !~ /Gate/ && $2 !~ /^-+$/ { printf "| %s | %s | %s | %s |\n", $2, $3, $4, $5 }' | sed 's/  */ /g'

echo
echo "## Questions"
echo
echo "| Status | Count |"; echo "|---|---|"
section Questions | awk -F'|' '/^\| RQ-/ { s=$5; gsub(/ /, "", s); n[s]++; c+=$6 } END { for (s in n) printf "| %s | %d |\n", s, n[s]; printf "| claims | %d |\n", c }'

echo
echo "## Dispatches (from §Log)"
echo
echo "| Stage | Rows | Resumes | Agents |"; echo "|---|---|---|---|"
section Log | awk -F'|' '
  /^\| / && $3 !~ /Stage/ && $3 !~ /^-/ {
    st=$3; gsub(/^ +| +$/, "", st); agent=$4
    n[st]++; if (agent ~ /resume/) r[st]++
    a=agent; sub(/ ·.*/, "", a); gsub(/^ +| +$/, "", a); if (!index(ag[st], a)) ag[st]=ag[st] a " "
    if (!(st in order)) { order[st]=++k; seq[k]=st }
  }
  END { for (i=1;i<=k;i++) { s=seq[i]; printf "| %s | %d | %d | %s|\n", s, n[s], r[s], ag[s] } }'

echo
echo "## Review"
echo
REVIEWS=("$W"/reviews/report-review-r*.md)
if [[ -f "${REVIEWS[0]}" ]]; then
  echo "| Round | Verdict | Majors | Minors |"; echo "|---|---|---|---|"
  for f in "${REVIEWS[@]}"; do
    r="${f##*-r}"; r="${r%.md}"
    v="$(grep -m1 '^verdict:' "$f" | sed 's/^verdict:[[:space:]]*//')"
    ma="$(grep -ciE '^\| *[A-Z]?[0-9]+ *\| *major' "$f" || true)"; mi="$(grep -ciE '^\| *[A-Z]?[0-9]+ *\| *minor' "$f" || true)"
    echo "| $r | $v | $ma | $mi |"
  done
else
  echo "No review files."
fi

# Rule hits: the Check column of every review finding, for this run.
THIS="$(mktemp)"; trap 'rm -f "$THIS"' EXIT
if [[ -f "${REVIEWS[0]}" ]]; then
  cat "${REVIEWS[@]}" | grep -oE '^\| *[A-Z]?[0-9]+ *\| *[A-Za-z]+ *\| *V[0-9]+' | grep -oE 'V[0-9]+$' | sort | uniq -c | awk '{ print $2 "\t" $1 }' > "$THIS"
fi
touch "$HITS"
{ grep -v "^$RUN	" "$HITS" || true; awk -v run="$RUN" -v d="$(date -u +%F)" -F'\t' '{ print run "\t" $1 "\t" $2 "\t" d }' "$THIS"; echo "$RUN	-	0	$(date -u +%F)"; } > "$HITS.tmp" && mv "$HITS.tmp" "$HITS"

echo
echo "## Reviewer checks"
echo
echo "| Check | Hits this run | Runs since last hit |"; echo "|---|---|---|"
CHECKS="$(grep -oE '^\| \*\*V[0-9]+' "$REVIEWER" 2>/dev/null | grep -oE 'V[0-9]+')"
RUNS="$(cut -f1 "$HITS" | awk '!s[$0]++')"
NRUNS="$(printf '%s\n' "$RUNS" | grep -c .)"
STALE=""
for c in $CHECKS; do
  here="$(awk -F'\t' -v c="$c" '$1==c { print $2 }' "$THIS")"
  since="$(printf '%s\n' "$RUNS" | awk -v c="$c" -v f="$HITS" '
    BEGIN { while ((getline l < f) > 0) { split(l, a, "\t"); if (a[2]==c && a[3]>0) hit[a[1]]=1 } }
    { run[NR]=$0 } END { n=0; for (i=NR; i>=1; i--) { if (run[i] in hit) break; n++ } print n }')"
  echo "| $c | ${here:-0} | $since |"
  [[ "$NRUNS" -ge 5 && "$since" -ge 5 ]] && STALE="$STALE $c"
done
echo
if [[ -n "$STALE" ]]; then
  echo "No hit in the last 5 runs:$STALE. Candidates to retire or merge; propose it below if the runs were representative."
else
  echo "Rule-hit history: $NRUNS run(s) in rule-hits.tsv; retirement candidates appear after 5."
fi

if [[ -f "$DEC" ]]; then
  echo
  echo "## Decisions"
  echo
  echo "| Source | Kind | Count |"; echo "|---|---|---|"
  grep -E '^source:' "$DEC" | sed -E 's/^source:[[:space:]]*([^ ·]+)[[:space:]]*·[[:space:]]*kind:[[:space:]]*([^ ]+).*/\1 \2/' | sort | uniq -c | awk '{ printf "| %s | %s | %d |\n", $2, $3, $1 }'
fi

echo
echo "## Costliest misses"
echo
echo "<!-- Lead: up to three. Where each was found, and where it could have been caught. -->"
echo
echo "## Proposed skill changes"
echo
echo "<!-- Lead: each names a file and line. Don't edit the skill. -->"
