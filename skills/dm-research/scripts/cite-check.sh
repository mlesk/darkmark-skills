#!/usr/bin/env bash
set -uo pipefail

# cite-check.sh — the mechanical citation check, run by the Lead before the
# review (the reviewer reads its file instead of redoing it). No judgment calls.
#
# Checks options.md and report.md against ledger.md, plan.md, and decisions.md:
#   C1 every cited claim (RQ###-C##, or R###/RQ###-C## from an earlier run) is in a ledger
#   C2 every cited L-C## is defined in plan.md
#   C3 every cited D-### is in decisions.md
#   C4 options.md has OPT-00 (the status quo)
#   C5 every row under options.md "## Scores" and "## Vetoes" cites a claim, L-C##, or ASM
#   C6 report.md labels each citation of a low-confidence claim "(low)", else of a single-source claim "(single-source)", right after the ID
#   C7 report.md is within the size's word cap (quick 1500 · standard 3000 · deep 5000)
#   C8 every K-1 (goal attainment) row under "## Scores" cites its L-C## derivation
#
# Usage: cite-check.sh --workspace DIR
# Writes <workspace>/reviews/cite-check.md. Exit 0 PASS · 1 FAIL · 2 could not run.

WORKSPACE=""
usage() { sed -n '4,19p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 2; }
while [[ $# -gt 0 ]]; do
  case "$1" in
    --workspace) WORKSPACE="$2"; shift 2 ;;
    -h|--help)   usage ;;
    *) echo "Unknown option: $1" >&2; usage ;;
  esac
done
[[ -n "$WORKSPACE" ]] || usage
W="$WORKSPACE"
for f in ledger.md options.md report.md state.md; do
  [[ -f "$W/$f" ]] || { echo "cite-check: missing $W/$f" >&2; exit 2; }
done
mkdir -p "$W/reviews"
OUT="$W/reviews/cite-check.md"
FAILS="$(mktemp)"; trap 'rm -f "$FAILS"' EXIT
fail() { echo "| $1 | $2 | $3 |" >> "$FAILS"; }

ids_in()   { grep -oE "$1" "${@:2}" 2>/dev/null | sed 's/^[^:]*://' | sort -u; }
CLAIM_RE='(R[0-9]{3}/)?RQ[0-9]{3}-C[0-9]{2}'
LEDGER_IDS="$(awk -F'|' '/^\| RQ[0-9]/ { gsub(/ /, "", $2); print $2 }' "$W/ledger.md" | sort -u)"

# C1 claims exist
for file in options.md report.md; do
  for id in $(grep -oE "$CLAIM_RE" "$W/$file" | sort -u); do
    case "$id" in
      R[0-9][0-9][0-9]/*)
        run="${id%%/*}"; cid="${id#*/}"
        prior="$(ls -d "$W"/../"$run"-*/ledger.md 2>/dev/null | head -1)"
        if [[ -z "$prior" ]] || ! grep -q "^| $cid |" "$prior"; then fail C1 "$file" "$id not found in run $run's ledger"; fi ;;
      *) printf '%s\n' "$LEDGER_IDS" | grep -qx "$id" || fail C1 "$file" "$id is not in ledger.md" ;;
    esac
  done
done

# C2 Lead inferences exist
for file in options.md report.md; do
  for id in $(grep -oE 'L-C[0-9]{2}' "$W/$file" | sort -u); do
    grep -qE "^(\| *|- *)?$id( |:|\|)" "$W/plan.md" 2>/dev/null || fail C2 "$file" "$id is not defined in plan.md"
  done
done

# C3 decisions exist
for file in options.md report.md; do
  for id in $(grep -oE 'D-[0-9]{3}' "$W/$file" | sort -u); do
    grep -qE "^## $id( |$)" "$W/decisions.md" 2>/dev/null || fail C3 "$file" "$id is not in decisions.md"
  done
done

# C4 status quo
grep -q 'OPT-00' "$W/options.md" || fail C4 options.md "no OPT-00 (status quo)"

# C5 every score and veto row cites evidence
awk '
  /^## / { sec = ($0 ~ /^## .*(Scores|Vetoes)/) ? $0 : ""; next }
  sec != "" && /^\| *(K-[0-9]|OPT-[0-9])/ {
    if ($0 !~ /RQ[0-9][0-9][0-9]-C[0-9][0-9]|L-C[0-9][0-9]|ASM-[0-9][0-9][0-9]/) {
      split($0, c, "|"); gsub(/^ +| +$/, "", c[2])
      printf "| C5 | options.md | %s row \"%s\" (line %d) cites no claim, L-C, or ASM |\n", sec, c[2], NR
    }
  }' "$W/options.md" >> "$FAILS"

# C8 goal-attainment scores show their derivation
awk '
  /^## / { sec = ($0 ~ /^## .*Scores/); next }
  sec && /^\| *K-1 *\|/ && $0 !~ /L-C[0-9][0-9]/ {
    printf "| C8 | options.md | K-1 row (line %d) cites no L-C## derivation (volume × price × margin basis) |\n", NR
  }' "$W/options.md" >> "$FAILS"

# C6 weak claims are labelled where the report cites them
awk -F'|' '/^\| RQ[0-9]/ {
  id = $2; gsub(/ /, "", id); conf = $8
  if (conf ~ /^ *low:/) print id "\tlow"; else if (conf ~ /single-source/) print id "\tsingle-source"
}' "$W/ledger.md" | while IFS=$'\t' read -r id label; do
  grep -noE "$id( \([^)]*\))?" "$W/report.md" | while IFS= read -r hit; do
    case "$hit" in *"($label"*|*", $label"*) ;; *) fail C6 report.md "line ${hit%%:*} cites $id without \"($label)\" right after it" ;; esac
  done
done

# C7 word cap
SIZE="$(grep -m1 '^size:' "$W/state.md" | sed 's/^size:[[:space:]]*//')"
case "$SIZE" in quick) CAP=1500 ;; standard) CAP=3000 ;; deep) CAP=5000 ;; *) CAP=0 ;; esac
WORDS="$(wc -w < "$W/report.md" | tr -d ' ')"
if [[ "$CAP" -eq 0 ]]; then fail C7 state.md "size \"$SIZE\" is not quick | standard | deep"
elif [[ "$WORDS" -gt "$CAP" ]]; then fail C7 report.md "$WORDS words, over the $SIZE cap of $CAP"; fi

N="$(grep -c . "$FAILS" || true)"
VERDICT=PASS; [[ "$N" -gt 0 ]] && VERDICT=FAIL
{
  echo "# Cite check"
  echo "verdict: $VERDICT"
  echo
  echo "Generated by scripts/cite-check.sh on $(date -u +%F). Ledger: $(printf '%s\n' "$LEDGER_IDS" | grep -c .) claims. Report: $WORDS words (cap $CAP)."
  echo
  if [[ "$N" -gt 0 ]]; then
    echo "| Check | File | Failure |"; echo "|---|---|---|"; cat "$FAILS"
  else
    echo "All checks C1–C8 passed."
  fi
} > "$OUT"
echo "cite-check: $VERDICT — $N failures · $OUT"
[[ "$VERDICT" == PASS ]]
