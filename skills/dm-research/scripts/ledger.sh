#!/usr/bin/env bash
set -uo pipefail

# ledger.sh — validates the claim rows in findings/RQ-###.md and builds the
# run's ledger.md from them. Run by each researcher on its own file (--check)
# before it returns, and by the Lead after every Return. No judgment calls.
#
# A row is rejected when: its ID is not RQ###-C## with the file's question
# number, or repeats; a column is empty; Kind is not fact | estimate |
# inference | opinion; a fact or opinion lacks a Source, an Accessed date
# (YYYY-MM-DD), or a Quote; Confidence doesn't start with "high:", "medium:",
# or "low:" plus a reason; an estimate has no "RQ###-C##:" derivation line;
# a "searched:" Source (a none-found claim) lists fewer than three searches.
# A file is also rejected when its ## Assumptions use ASM-### (the Lead's)
# instead of RQ###-A##.
#
# Usage:
#   ledger.sh --workspace DIR                 # check all findings, write ledger.md
#   ledger.sh --workspace DIR --check FILE    # check one findings file only
#
# Exit 0 PASS · 1 rejected rows (listed on stdout) · 2 could not run.

WORKSPACE="" CHECK=""
usage() { sed -n '4,17p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 2; }
while [[ $# -gt 0 ]]; do
  case "$1" in
    --workspace) WORKSPACE="$2"; shift 2 ;;
    --check)     CHECK="$2"; shift 2 ;;
    -h|--help)   usage ;;
    *) echo "Unknown option: $1" >&2; usage ;;
  esac
done
[[ -n "$WORKSPACE" && -d "$WORKSPACE" ]] || usage

if [[ -n "$CHECK" ]]; then
  [[ -f "$CHECK" ]] || { echo "ledger: no $CHECK" >&2; exit 2; }
  FILES=("$CHECK")
else
  FILES=()
  for f in "$WORKSPACE"/findings/RQ-*.md; do [[ -f "$f" ]] && FILES+=("$f"); done
  [[ ${#FILES[@]} -gt 0 ]] || { echo "ledger: no findings in $WORKSPACE/findings" >&2; exit 2; }
fi

ROWS="$(mktemp)"; ERRS="$(mktemp)"
trap 'rm -f "$ROWS" "$ERRS"' EXIT

awk -v rows="$ROWS" -v errs="$ERRS" '
  function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
  function nil(s)  { return s == "" || s == "-" || s == "–" || s == "—" }
  function err(m)  { printf "%s: %s\n", FILENAME, m >> errs }
  FNR == 1 {
    sec = ""; rq = FILENAME; sub(/.*RQ-/, "", rq); sub(/\.md$/, "", rq)
  }
  /^## / { sec = $0; next }
  sec ~ /^## Assumptions/ && /^[-* ]*ASM-[0-9]/ { err("assumption \"" trim($0) "\": researchers number assumptions RQ" rq "-A##; ASM-### is the Lead'\''s"); next }
  sec ~ /^## Derivations/ && match($0, /RQ[0-9][0-9][0-9]-C[0-9][0-9]:/) {
    derived[substr($0, RSTART, RLENGTH - 1)] = 1; next
  }
  sec ~ /^## Claims/ && /^\|/ {
    n = split($0, c, "|")
    id = trim(c[2])
    if (id == "ID" || id ~ /^-+$/ || id ~ /^:?-+:?$/) next
    if (n < 9) { err(id ": expected 7 columns, found " (n - 2)); next }
    kind = trim(c[4]); src = trim(c[5]); acc = trim(c[6]); quote = trim(c[7]); conf = trim(c[8])
    if (id !~ /^RQ[0-9][0-9][0-9]-C[0-9][0-9]$/) err(id ": ID is not RQ###-C##")
    else if (substr(id, 3, 3) != rq) err(id ": ID does not match the file RQ-" rq)
    if (id in seen) err(id ": duplicate ID"); seen[id] = 1
    if (nil(trim(c[3]))) err(id ": empty Claim")
    if (kind !~ /^(fact|estimate|inference|opinion)$/) err(id ": Kind \"" kind "\" is not fact | estimate | inference | opinion")
    if (kind == "fact" || kind == "opinion") {
      if (nil(src))   err(id ": a " kind " needs a Source")
      if (acc !~ /^[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]$/) err(id ": Accessed \"" acc "\" is not YYYY-MM-DD")
      if (nil(quote)) err(id ": a " kind " needs a Quote")
    }
    if (src ~ /^searched:/ && split(src, q, ";") < 3) err(id ": a none-found claim needs at least three searches, \"searched: q1; q2; q3\"")
    if (conf !~ /^(high|medium|low):[ ]*[^ ]/) err(id ": Confidence must be high: | medium: | low: with a reason")
    if (kind == "estimate") estimates[id] = FILENAME
    print id "\t" trim(c[3]) "\t" kind "\t" src "\t" acc "\t" quote "\t" conf >> rows
  }
  END {
    for (id in estimates) if (!(id in derived)) printf "%s: %s: an estimate needs a \"%s:\" line under ## Derivations\n", estimates[id], id, id >> errs
  }
' "${FILES[@]}"

if [[ -s "$ERRS" ]]; then
  sort "$ERRS"
  echo "ledger: FAIL — $(wc -l < "$ERRS" | tr -d ' ') rejected"
  exit 1
fi

N="$(wc -l < "$ROWS" | tr -d ' ')"
if [[ -z "$CHECK" ]]; then
  {
    echo "# Ledger"
    echo
    echo "Generated by scripts/ledger.sh on $(date -u +%F) from findings/. Do not edit by hand. $N claims."
    echo
    echo "| ID | Claim | Kind | Source | Accessed | Quote | Confidence |"
    echo "|---|---|---|---|---|---|---|"
    sort "$ROWS" | awk -F'\t' '{ printf "| %s | %s | %s | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5, $6, $7 }'
  } > "$WORKSPACE/ledger.md"
fi
echo "ledger: PASS — $N claims"
exit 0
