#!/usr/bin/env bash
set -uo pipefail

# retro.sh — generates the measured part of retro.md from state.md, decisions.md
# and costs.tsv, so the Lead writes only the judgment: the costliest failures,
# where each defect was found against where it could have been, and the
# proposed skill changes.
#
# Usage: retro.sh --workspace DIR > <workspace>/retro.md   (then append the judgment)

WORKSPACE=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --workspace) WORKSPACE="$2"; shift 2 ;;
    *) sed -n '4,10p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 2 ;;
  esac
done
STATE="$WORKSPACE/state.md"; DEC="$WORKSPACE/decisions.md"; COSTS="$WORKSPACE/costs.tsv"
[[ -f "$STATE" ]] || { echo "retro: no $STATE" >&2; exit 2; }
field() { grep -m1 "^$1:" "$STATE" | sed "s/^$1:[[:space:]]*//"; }
trim() { sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//'; }
section() { awk -v h="## $1" 'index($0,h)==1{on=1; next} on && /^## /{exit} on' "$STATE"; }

echo "# Retro: $(field run)"
echo
echo "Run: $(field kind), size $(field size), mode $(field mode), quality bar $(field quality-bar), max-parallel $(field max-parallel). Generated by scripts/retro.sh on $(date -u +%F)."
echo
echo "## Gates"
echo
echo "| Gate | Status | Round | Notes |"; echo "|---|---|---|---|"
section Gates | awk -F'|' '/^\| / && $2 !~ /Gate/ { printf "| %s | %s | %s | %s |\n", $2, $4, $5, $7 }' | sed 's/  */ /g'

echo
echo "## Build"
echo
BUILD="$(section Build | grep -E '^\| PHASE-')"
N_PH="$(printf '%s\n' "$BUILD" | grep -cE '^\| PHASE-[0-9]+' || true)"
N_FIX="$(printf '%s\n' "$BUILD" | grep -cE '^\| PHASE-F' || true)"
N_DONE="$(printf '%s\n' "$BUILD" | awk -F'|' '{gsub(/ /,"",$4)} $4=="done"' | grep -c . || true)"
N_REV="$(printf '%s\n' "$BUILD" | awk -F'|' '{gsub(/ /,"",$7); n+=$7} END{print n+0}')"
N_ESC="$(printf '%s\n' "$BUILD" | awk -F'|' '{gsub(/ /,"",$4)} $4=="escalated"' | grep -c . || true)"
echo "| Phases | Fix phases | Done | REVISE rounds | Escalated |"; echo "|---|---|---|---|---|"
echo "| $N_PH | $N_FIX | $N_DONE | $N_REV | $N_ESC |"

echo
echo "## Dispatches (from §Log)"
echo
echo "| Stage | Rows | Resumes | REVISE | PASS | blocked | Agents |"; echo "|---|---|---|---|---|---|---|"
section Log | awk -F'|' '
  /^\| / && $3 !~ /Stage/ && $3 !~ /^-/ {
    st=$3; gsub(/^ +| +$/, "", st); agent=$4; res=$7
    n[st]++; if (agent ~ /resume/) r[st]++
    if (res ~ /REVISE/) rv[st]++; if (res ~ /PASS|done|green/) ok[st]++; if (res ~ /blocked/) bl[st]++
    a=agent; sub(/ ·.*/, "", a); gsub(/^ +| +$/, "", a); sub(/ \(.*/, "", a); if (!index(ag[st], a)) ag[st]=ag[st] a " "
    if (!(st in order)) { order[st]=++k; seq[k]=st }
  }
  END { for (i=1;i<=k;i++) { s=seq[i]; printf "| %s | %d | %d | %d | %d | %d | %s|\n", s, n[s], r[s], rv[s], ok[s], bl[s], ag[s] } }'

if [[ -f "$DEC" ]]; then
  echo
  echo "## Decisions"
  echo
  TOTAL="$(grep -cE '^## D-[0-9]+' "$DEC" || true)"
  echo "$TOTAL decisions: $(grep -E '^source:' "$DEC" | sed -E 's/.*kind:[[:space:]]*//; s/[[:space:]]*\(.*//' | sort | uniq -c | awk '{printf "%s %s · ", $1, $2}' | sed 's/ · $//'). Sources: $(grep -E '^source:' "$DEC" | sed -E 's/^source:[[:space:]]*//; s/[[:space:]]*·.*//; s/[[:space:]]*\(.*//' | sort | uniq -c | awk '{printf "%s %s · ", $1, $2}' | sed 's/ · $//')."
  SUP="$(grep -E '^affects:.*supersedes:' "$DEC" | grep -oE 'supersedes:[[:space:]]*D-[0-9]+' | wc -l | trim)"
  echo "Superseded: $SUP."
fi

if [[ -f "$COSTS" ]]; then
  echo
  echo "## Cost per session (costs.tsv)"
  echo
  echo "| Sessions | Cost USD | Turns | Hours |"; echo "|---|---|---|---|"
  awk -F'\t' 'NR>1 { n++; c+=$4; t+=$5; d+=$6 } END { printf "| %d | %.2f | %d | %.1f |\n", n, c, t, d/3600000 }' "$COSTS"
else
  echo
  echo "Costs: no costs.tsv (the run was not driven by run.sh); note the host's /cost figure here."
fi

echo
echo "## Open items at close"
echo
section "Open items" | grep -E '^- |^\| ' | head -20
cat <<'TAIL'

## The three costliest failures

<for each: what, where it was found, where it could have been found, what it cost>

## Proposed changes to the skill (not edited)

<each naming the file and line>
TAIL
